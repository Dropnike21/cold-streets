-- Trade Network / Player Bazaar escrow foundation.
-- No listing mutation is enabled by this migration. Settlement currency, fees,
-- partial-fill behavior and expiry remain source-unresolved.

CREATE TABLE public.trade_listings (
  listing_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seller_id bigint NOT NULL REFERENCES public.users(user_id),
  item_id bigint NOT NULL REFERENCES public.items_master(item_id),
  quantity_total bigint NOT NULL,
  quantity_remaining bigint NOT NULL,
  asking_price numeric,
  settlement_currency text,
  status text NOT NULL DEFAULT 'draft',
  idempotency_key uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  closed_at timestamptz,
  CONSTRAINT trade_listings_quantity_total_positive
    CHECK (quantity_total > 0),
  CONSTRAINT trade_listings_quantity_remaining_range
    CHECK (quantity_remaining >= 0 AND quantity_remaining <= quantity_total),
  CONSTRAINT trade_listings_price_positive_integer
    CHECK (
      asking_price IS NULL
      OR (asking_price > 0 AND asking_price = trunc(asking_price))
    ),
  CONSTRAINT trade_listings_currency_check
    CHECK (
      settlement_currency IS NULL
      OR settlement_currency IN ('dirty_cash','clean_cash')
    ),
  CONSTRAINT trade_listings_status_check
    CHECK (status IN ('draft','open','reserved','closed','cancelled','voided')),
  CONSTRAINT trade_listings_closed_state_check
    CHECK (
      (status IN ('closed','cancelled','voided') AND closed_at IS NOT NULL)
      OR
      (status NOT IN ('closed','cancelled','voided') AND closed_at IS NULL)
    ),
  CONSTRAINT trade_listings_open_contract_check
    CHECK (
      status NOT IN ('open','reserved')
      OR (asking_price IS NOT NULL AND settlement_currency IS NOT NULL)
    )
);

CREATE UNIQUE INDEX trade_listings_seller_idempotency_unique_idx
  ON public.trade_listings (seller_id, idempotency_key)
  WHERE idempotency_key IS NOT NULL;

CREATE INDEX trade_listings_item_status_idx
  ON public.trade_listings (item_id, status, created_at DESC);

CREATE INDEX trade_listings_seller_status_idx
  ON public.trade_listings (seller_id, status, created_at DESC);

ALTER TABLE public.trade_listings ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.trade_listings FROM anon, authenticated;

CREATE TABLE public.trade_listing_events (
  event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  listing_id bigint NOT NULL REFERENCES public.trade_listings(listing_id),
  actor_user_id bigint REFERENCES public.users(user_id),
  event_type text NOT NULL,
  quantity_delta bigint NOT NULL DEFAULT 0,
  amount numeric,
  currency text,
  source_ref text,
  metadata_jsonb jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT trade_listing_events_type_nonempty
    CHECK (btrim(event_type) <> ''),
  CONSTRAINT trade_listing_events_amount_integer
    CHECK (amount IS NULL OR amount = trunc(amount)),
  CONSTRAINT trade_listing_events_currency_check
    CHECK (currency IS NULL OR currency IN ('dirty_cash','clean_cash')),
  CONSTRAINT trade_listing_events_amount_currency_pair
    CHECK (
      (amount IS NULL AND currency IS NULL)
      OR
      (amount IS NOT NULL AND currency IS NOT NULL)
    ),
  CONSTRAINT trade_listing_events_source_ref_nonempty
    CHECK (source_ref IS NULL OR btrim(source_ref) <> ''),
  CONSTRAINT trade_listing_events_metadata_object
    CHECK (jsonb_typeof(metadata_jsonb) = 'object')
);

CREATE UNIQUE INDEX trade_listing_events_source_unique_idx
  ON public.trade_listing_events (listing_id, event_type, source_ref)
  WHERE source_ref IS NOT NULL;

CREATE INDEX trade_listing_events_listing_created_idx
  ON public.trade_listing_events (listing_id, created_at DESC, event_id DESC);

ALTER TABLE public.trade_listing_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.trade_listing_events FROM anon, authenticated;
