-- Consent-based real-player company employment offers.
-- Source: Player-Owned Companies design says real players require negotiated
-- Clean Cash salaries. Payroll execution remains separately paused.

CREATE UNIQUE INDEX company_employees_one_real_company_per_player_idx
  ON public.company_employees (employee_id)
  WHERE is_npc = false;

CREATE TABLE public.company_employment_offers (
  offer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id bigint NOT NULL
    REFERENCES public.company_applicants(application_id),
  company_id bigint NOT NULL
    REFERENCES public.player_companies(company_id),
  employee_id bigint NOT NULL
    REFERENCES public.users(user_id),
  offered_by bigint NOT NULL
    REFERENCES public.users(user_id),
  position_id bigint NOT NULL
    REFERENCES public.company_positions_master(position_id),
  daily_salary_clean numeric NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  source_ref uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  responded_at timestamptz,

  CONSTRAINT company_employment_offers_salary_positive_integer
    CHECK (
      daily_salary_clean > 0
      AND daily_salary_clean = trunc(daily_salary_clean)
    ),
  CONSTRAINT company_employment_offers_status_check
    CHECK (status IN ('pending','accepted','rejected','withdrawn')),
  CONSTRAINT company_employment_offers_response_state_check
    CHECK (
      (status = 'pending' AND responded_at IS NULL)
      OR
      (status <> 'pending' AND responded_at IS NOT NULL)
    )
);

CREATE UNIQUE INDEX company_employment_offers_source_unique_idx
  ON public.company_employment_offers (offered_by, source_ref);

CREATE UNIQUE INDEX company_employment_offers_one_pending_application_idx
  ON public.company_employment_offers (application_id)
  WHERE status = 'pending';

CREATE INDEX company_employment_offers_employee_status_idx
  ON public.company_employment_offers (employee_id, status, created_at DESC);

CREATE INDEX company_employment_offers_company_status_idx
  ON public.company_employment_offers (company_id, status, created_at DESC);

CREATE INDEX company_employment_offers_position_idx
  ON public.company_employment_offers (position_id);

ALTER TABLE public.company_employment_offers ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.company_employment_offers FROM anon, authenticated;
