-- Company cash-flow reconciliation.
-- Only owner Dirty Cash funding is executable at this stage.
-- Laundering conversion, payroll settlement, sales revenue, withdrawals,
-- advertising spend and bankruptcy settlement remain paused.

CREATE TABLE public.company_cash_ledger (
    entry_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id bigint NOT NULL
        REFERENCES public.player_companies(company_id),
    actor_user_id bigint
        REFERENCES public.users(user_id),
    event_type text NOT NULL,
    dirty_delta numeric NOT NULL DEFAULT 0,
    clean_delta numeric NOT NULL DEFAULT 0,
    dirty_balance_after numeric NOT NULL,
    clean_balance_after numeric NOT NULL,
    source_ref text,
    metadata_jsonb jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT company_cash_ledger_event_type_nonempty
        CHECK (btrim(event_type) <> ''),
    CONSTRAINT company_cash_ledger_dirty_delta_integer
        CHECK (dirty_delta = trunc(dirty_delta)),
    CONSTRAINT company_cash_ledger_clean_delta_integer
        CHECK (clean_delta = trunc(clean_delta)),
    CONSTRAINT company_cash_ledger_nonzero_delta
        CHECK (dirty_delta <> 0 OR clean_delta <> 0),
    CONSTRAINT company_cash_ledger_dirty_balance_nonnegative_integer
        CHECK (
            dirty_balance_after >= 0
            AND dirty_balance_after = trunc(dirty_balance_after)
        ),
    CONSTRAINT company_cash_ledger_clean_balance_nonnegative_integer
        CHECK (
            clean_balance_after >= 0
            AND clean_balance_after = trunc(clean_balance_after)
        ),
    CONSTRAINT company_cash_ledger_source_ref_nonempty
        CHECK (source_ref IS NULL OR btrim(source_ref) <> ''),
    CONSTRAINT company_cash_ledger_metadata_object
        CHECK (jsonb_typeof(metadata_jsonb) = 'object')
);

CREATE INDEX company_cash_ledger_company_created_idx
    ON public.company_cash_ledger (company_id, created_at DESC, entry_id DESC);

CREATE UNIQUE INDEX company_cash_ledger_source_unique_idx
    ON public.company_cash_ledger (company_id, event_type, source_ref)
    WHERE source_ref IS NOT NULL;

ALTER TABLE public.company_cash_ledger ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.company_cash_ledger FROM anon, authenticated;

ALTER TABLE public.player_companies
    ADD CONSTRAINT player_companies_daily_income_nonnegative_integer_check
    CHECK (daily_income >= 0 AND daily_income = trunc(daily_income));

ALTER TABLE public.company_types_master
    ADD CONSTRAINT company_types_tier_check
    CHECK (tier BETWEEN 1 AND 3);

ALTER TABLE public.company_types_master
    ADD CONSTRAINT company_types_setup_cost_nonnegative_integer_check
    CHECK (setup_cost >= 0 AND setup_cost = trunc(setup_cost));

ALTER TABLE public.company_types_master
    ADD CONSTRAINT company_types_daily_upkeep_nonnegative_integer_check
    CHECK (daily_upkeep >= 0 AND daily_upkeep = trunc(daily_upkeep));
