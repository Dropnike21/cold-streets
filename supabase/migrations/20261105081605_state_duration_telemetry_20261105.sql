CREATE TABLE public.user_state_episodes (
  episode_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL
    REFERENCES public.users(user_id) ON DELETE CASCADE,
  state_type text NOT NULL,
  started_at timestamptz NOT NULL,
  scheduled_end_at timestamptz NOT NULL,
  ended_at timestamptz,
  end_reason text,
  source_type text NOT NULL,
  source_ref text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT user_state_episodes_state_check
    CHECK (state_type IN ('jail','hospital')),
  CONSTRAINT user_state_episodes_window_check
    CHECK (scheduled_end_at > started_at),
  CONSTRAINT user_state_episodes_end_window_check
    CHECK (
      ended_at IS NULL OR
      (ended_at >= started_at AND ended_at <= scheduled_end_at)
    ),
  CONSTRAINT user_state_episodes_end_reason_check
    CHECK (
      (ended_at IS NULL AND end_reason IS NULL)
      OR
      (ended_at IS NOT NULL AND end_reason IS NOT NULL AND btrim(end_reason) <> '')
    ),
  CONSTRAINT user_state_episodes_source_type_nonempty
    CHECK (btrim(source_type) <> ''),
  CONSTRAINT user_state_episodes_source_ref_nonempty
    CHECK (btrim(source_ref) <> '')
);

CREATE UNIQUE INDEX user_state_episodes_one_open_per_user_idx
  ON public.user_state_episodes (user_id)
  WHERE ended_at IS NULL;

CREATE INDEX user_state_episodes_user_state_started_idx
  ON public.user_state_episodes (user_id, state_type, started_at);

CREATE INDEX user_state_episodes_due_idx
  ON public.user_state_episodes (scheduled_end_at, episode_id)
  WHERE ended_at IS NULL;

ALTER TABLE public.user_state_episodes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.user_state_episodes FROM anon, authenticated;
