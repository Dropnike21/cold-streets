CREATE TABLE IF NOT EXISTS public.user_premium_pack_inventory (
  user_id bigint NOT NULL
    REFERENCES public.users(user_id) ON DELETE CASCADE,
  pack_key text NOT NULL
    REFERENCES public.premium_pack_catalog(pack_key),
  quantity bigint NOT NULL DEFAULT 0,
  reserved_quantity bigint NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, pack_key),
  CONSTRAINT premium_pack_inventory_quantity_check CHECK (quantity >= 0),
  CONSTRAINT premium_pack_inventory_reserved_check CHECK (
    reserved_quantity >= 0 AND reserved_quantity <= quantity
  )
);

CREATE TABLE IF NOT EXISTS public.user_premium_entitlements (
  entitlement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL
    REFERENCES public.users(user_id) ON DELETE CASCADE,
  benefit_tier text NOT NULL,
  starts_at timestamptz NOT NULL,
  ends_at timestamptz NOT NULL,
  source_type text NOT NULL,
  source_ref text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT premium_entitlement_tier_check CHECK (
    benefit_tier IN ('vip', 'kingpin')
  ),
  CONSTRAINT premium_entitlement_window_check CHECK (ends_at > starts_at),
  CONSTRAINT premium_entitlement_source_type_check CHECK (
    source_type IN ('pack_consumption', 'subscription')
  ),
  CONSTRAINT premium_entitlement_source_ref_nonempty CHECK (
    btrim(source_ref) <> ''
  ),
  CONSTRAINT premium_entitlement_source_unique UNIQUE (
    user_id, source_type, source_ref
  )
);

CREATE INDEX IF NOT EXISTS user_premium_entitlements_active_idx
  ON public.user_premium_entitlements (user_id, benefit_tier, ends_at);

CREATE TABLE IF NOT EXISTS public.user_subscriptions (
  user_id bigint PRIMARY KEY
    REFERENCES public.users(user_id) ON DELETE CASCADE,
  subscription_tier text NOT NULL DEFAULT 'subscriber',
  status text NOT NULL,
  current_period_start timestamptz NOT NULL,
  current_period_end timestamptz NOT NULL,
  cancel_at_period_end boolean NOT NULL DEFAULT false,
  source_ref text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT user_subscription_tier_check CHECK (
    subscription_tier = 'subscriber'
  ),
  CONSTRAINT user_subscription_status_check CHECK (
    status IN ('active', 'cancelled', 'expired', 'past_due')
  ),
  CONSTRAINT user_subscription_period_check CHECK (
    current_period_end > current_period_start
  ),
  CONSTRAINT user_subscription_source_ref_nonempty CHECK (
    btrim(source_ref) <> ''
  )
);

