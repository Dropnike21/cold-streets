CREATE TABLE IF NOT EXISTS public.premium_pack_catalog (
  pack_key text PRIMARY KEY,
  display_name text NOT NULL UNIQUE,
  duration_days integer NOT NULL,
  is_tradable boolean NOT NULL DEFAULT true,
  activation_available boolean NOT NULL DEFAULT false,
  max_energy_override bigint,
  nerve_bonus_percent integer,
  nerve_semantics text,
  casino_daily_spend_cap bigint,
  benefit_notes text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT premium_pack_key_nonempty CHECK (btrim(pack_key) <> ''),
  CONSTRAINT premium_pack_duration_positive CHECK (duration_days > 0),
  CONSTRAINT premium_pack_energy_positive CHECK (
    max_energy_override IS NULL OR max_energy_override > 0
  ),
  CONSTRAINT premium_pack_nerve_percent_check CHECK (
    nerve_bonus_percent IS NULL OR nerve_bonus_percent BETWEEN 0 AND 1000
  ),
  CONSTRAINT premium_pack_casino_cap_positive CHECK (
    casino_daily_spend_cap IS NULL OR casino_daily_spend_cap > 0
  )
);

