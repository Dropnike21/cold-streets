CREATE TABLE public.casino_token_spend_ledger (
  spend_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.users(user_id),
  game_key text NOT NULL,
  token_amount bigint NOT NULL,
  source_ref text NOT NULL,
  spent_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT casino_token_spend_game_nonempty
    CHECK (btrim(game_key) <> ''),
  CONSTRAINT casino_token_spend_amount_check
    CHECK (token_amount >= 1 AND token_amount <= 100),
  CONSTRAINT casino_token_spend_source_nonempty
    CHECK (btrim(source_ref) <> ''),
  CONSTRAINT casino_token_spend_source_unique
    UNIQUE (user_id, source_ref)
);

CREATE INDEX casino_token_spend_user_time_idx
  ON public.casino_token_spend_ledger (user_id, spent_at);

ALTER TABLE public.casino_token_spend_ledger ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.casino_token_spend_ledger
  FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.prevent_casino_token_spend_mutation()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
BEGIN
  RAISE EXCEPTION 'casino token spend ledger rows are immutable';
END;
$$;

REVOKE ALL ON FUNCTION public.prevent_casino_token_spend_mutation()
  FROM PUBLIC, anon, authenticated;

CREATE TRIGGER casino_token_spend_immutable_update
BEFORE UPDATE ON public.casino_token_spend_ledger
FOR EACH ROW
EXECUTE FUNCTION public.prevent_casino_token_spend_mutation();

CREATE TRIGGER casino_token_spend_immutable_delete
BEFORE DELETE ON public.casino_token_spend_ledger
FOR EACH ROW
EXECUTE FUNCTION public.prevent_casino_token_spend_mutation();
